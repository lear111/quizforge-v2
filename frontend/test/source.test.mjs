import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readdir,readFile,access} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve,dirname} from 'node:path';
import {execFileSync} from 'node:child_process';

const root=fileURLToPath(new URL('..',import.meta.url));
async function all(directory) {
  const files=[];for(const item of await readdir(directory,{withFileTypes:true})) {
    const path=resolve(directory,item.name);if(item.isDirectory())files.push(...await all(path));else files.push(path);
  }return files;
}
test('fork modules parse and every relative module dependency exists',async()=>{
  for(const path of await all(resolve(root,'practice')))if(path.endsWith('.js')) {
    const source=await readFile(path,'utf8');
    execFileSync(process.execPath,['--check',path]);
    for(const match of source.matchAll(/\bfrom\s+['"](\.[^'"]+)['"]/g))await access(resolve(dirname(path),match[1]));
  }
});
test('no old auth transport or removed feature entry survives',async()=>{
  const source=(await Promise.all((await all(resolve(root,'practice'))).filter(path=>/\.(js|html)$/.test(path)).map(path=>readFile(path,'utf8')))).join('\n');
  for(const forbidden of ['X-QuizForge-Token','sessionStorage','quizforge-access-token','id="access-dialog"','id="edit-open"','id="network-settings-open"','id="settings-development-tab"','id="settings-ai-tab"','id="show-extensions"'])assert.ok(!source.includes(forbidden),forbidden);
});
test('all entry assets exist and have an absolute practice path',async()=>{
  const html=await readFile(resolve(root,'practice/index.html'),'utf8');
  for(const match of html.matchAll(/(?:src|href)="([^"]+)"/g)) {
    const path=match[1];if(path==='/')continue;
    assert.ok(path.startsWith('/practice/'),path);await access(resolve(root,path.slice(1)));
  }
  const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(match=>match[1]);assert.equal(new Set(ids).size,ids.length,'duplicate IDs');
});
test('shared richtext bundles are generated by the upstream scripts',async()=>{
  for(const version of ['1.0.0','1.1.3'])for(const name of ['richtext.js','richtext-editor.js','THIRD_PARTY_NOTICES.md'])await access(resolve(root,'shared/richtext',version,name));
});
