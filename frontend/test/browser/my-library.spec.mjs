import {test,expect} from '@playwright/test';
import {registerByApi} from './accounts.mjs';
import {uploadAndImportFromLibrary} from './library-fixture.mjs';
import {resolve} from 'node:path';
import {mkdir} from 'node:fs/promises';

test('my library uploads, imports independent practice, downloads original and preserves practice after deletion',async({page},info)=>{
  test.skip(process.env.QF_READ_BROWSER_TESTS !== '1','需要独立本机 Compose');
  test.setTimeout(180000);
  const errors = [];
  page.on('pageerror',error=>errors.push(error.message));
  await registerByApi(page,'my-library','我的题库验收');
  await page.goto('/');
  await page.getByRole('link',{name:'我的题库',exact:true}).click();
  const {packId,collections} = await uploadAndImportFromLibrary(page);
  expect(collections).toHaveLength(5);
  await expect(page.locator('#detail')).toContainText('已审核 · 通过');
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('link',{name:'下载原文件',exact:true}).click();
  const downloaded = await downloadEvent;
  expect(downloaded.suggestedFilename()).toBe('basic-types.qbank');
  const {readFile} = await import('node:fs/promises');
  expect(await readFile(await downloaded.path())).toEqual(await readFile(resolve('../samples/basic-types.qbank')));
  const repeated = page.waitForResponse(response=>new URL(response.url()).pathname===`/api/library/packs/${packId}/practice`);
  await page.getByRole('button',{name:'导入练习空间',exact:true}).click();
  const copies = (await (await repeated).json()).collections;
  expect(copies[0].id).not.toBe(collections[0].id);
  expect(copies[0].title).toBe(collections[0].title+'（2）');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const screenshots=resolve(process.env.QF_SCREENSHOT_DIR||'../.artifacts/local/my-library/screenshots');
  await mkdir(screenshots,{recursive:true});
  await page.screenshot({path:resolve(screenshots,`${info.project.name}-my-library.png`),fullPage:true});
  await page.getByRole('button',{name:'直接发布到广场',exact:true}).click();
  const publish = page.locator('[data-publish-form]');
  await publish.locator('[name=title]').fill('我的公开题库');
  await publish.locator('[name=summary]').fill('浏览器合成样例');
  await publish.locator('[name=description]').fill('仅用于本机验证原文件发布');
  await publish.locator('[name=rights]').check();
  await publish.getByRole('button',{name:'用原文件发布',exact:true}).click();
  await expect(page.locator('#notice')).toContainText('公开版本仍需管理员审核');
  await expect(page.locator('#packages')).toContainText('我的公开发布');
  await page.locator(`[data-pack-id="${packId}"]`).getByRole('button').click();
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'删除此资源',exact:true}).click();
  await expect(page.locator(`[data-pack-id="${packId}"]`)).toHaveCount(0);
  await page.goto('/practice/');
  await expect(page.locator('#document-title')).not.toBeEmpty();
  await expect(page.locator('.question-pane:not([hidden]) iframe.question-frame:not([data-candidate])')).toBeVisible({timeout:30000});
  await expect(page.locator('#library-import')).toHaveCount(0);
  expect(errors).toEqual([]);
});

test('rejected upload can be replaced inside the same entry and keeps prior result',async({page})=>{
  test.skip(process.env.QF_READ_BROWSER_TESTS !== '1','需要独立本机 Compose');
  test.setTimeout(180000);
  await registerByApi(page,'my-library-retry','重新上传验收');
  await page.goto('/library/');
  const accepted = page.waitForResponse(response=>new URL(response.url()).pathname==='/api/library/uploads');
  await page.locator('#upload-file').setInputFiles({name:'bad.qbank',mimeType:'application/octet-stream',buffer:Buffer.from('invalid')});
  expect((await accepted).status()).toBe(202);
  await expect(page.locator('[data-pack-id]').first()).toBeVisible();
  const packId = await page.locator('[data-pack-id]').first().getAttribute('data-pack-id');
  await expect(page.locator('#detail')).toContainText('已审核 · 未通过',{timeout:60000});
  const picker = page.waitForEvent('filechooser');
  await page.getByRole('button',{name:'在此条目重新上传'}).click();
  const revised = page.waitForResponse(response=>new URL(response.url()).pathname==='/api/library/uploads');
  await (await picker).setFiles(resolve('../samples/single-choice.qbank'));
  expect((await revised).status()).toBe(202);
  await expect(page.locator('#detail [data-revision="2"]')).toBeVisible();
  const current = await page.request.get(`/api/library/packs/${packId}`);
  expect((await current.json()).revisions.map(version=>version.revision)).toEqual([2,1]);
  await expect(page.locator('#detail [data-revision="1"]')).toContainText('已审核 · 未通过');
  await expect(page.locator('#detail [data-revision="2"]')).toBeVisible();
});
