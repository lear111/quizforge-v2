import {test,expect as baseExpect} from '@playwright/test';
import {execFileSync} from 'node:child_process';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
const expect=baseExpect.configure({timeout:30000});

test('answer text, image and ink are captured before submit; both board layers survive refresh',async({page},info)=>{
  test.skip(process.env.QF_READ_BROWSER_TESTS!=='1','Requires an isolated Compose fixture');
  test.setTimeout(180000);page.setDefaultTimeout(30000);
  const project=process.env.QF_COMPOSE_PROJECT;
  if(!project?.startsWith('qf-'))throw Error('Use an isolated qf-* Compose project');
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');const origin=new URL(page.url()).origin;
  expect((await page.request.post('/api/auth/register',{headers:{Origin:origin},data:{email:`whiteboard-${crypto.randomUUID()}@example.test`,name:'白板资源验收',password:'password123'}})).status()).toBe(200);
  const imported=await page.request.post('/api/library/import',{headers:{Origin:origin},multipart:{file:{name:'basic-types.qbank',mimeType:'application/zip',buffer:await readFile(resolve('../samples/basic-types.qbank'))}}});
  expect(imported.status()).toBe(200);
  const collection=(await imported.json()).collections.find(row=>row.title==='简答题（答题区）');
  expect(collection.id).toMatch(/^[a-f0-9-]{36}$/);
  const query=`INSERT INTO admin_extension_review (digest,extension_id,version,status) SELECT DISTINCT e.digest,e.extension_id,e.version,'approved' FROM content_extension_package e JOIN content_question q ON q.extension_digest=e.digest JOIN practice_collection c ON c.bank_id=q.bank_id WHERE c.id='${collection.id}' ON DUPLICATE KEY UPDATE status='approved';`;
  execFileSync('docker',['compose','-p',project,'-f',resolve('../deploy/docker-compose.yml'),'exec','-T','mysql','sh','-c','exec mysql --user="$MYSQL_USER" --password="$MYSQL_PASSWORD" "$MYSQL_DATABASE"'],{input:query,stdio:['pipe','pipe','pipe']});
  const overview=await (await page.request.get(`/api/collections/bank/${collection.id}`)).json();
  const path=`/api/collections/bank/${collection.id}/questions/${encodeURIComponent(overview.questions[0].id)}`;
  const read=async()=>{const response=await page.request.get(path);expect(response.status()).toBe(200);return response.json();};
  const open=async()=>{
    await page.goto('/practice/');
    await expect(page.locator('.question-pane:not([hidden]):not([inert]) iframe.question-frame')).toHaveCount(1);
    await expect(page.locator('#collection-loading')).toBeHidden();
    if(await page.locator('#library-toggle').getAttribute('aria-expanded')!=='true')await page.locator('#library-toggle').click();
    await page.locator(`.library-item[data-item-id="${collection.id}"]`).click();
    await expect(page.locator('#document-title')).toHaveText(collection.title);
    await expect(page.locator('#collection-loading')).toBeHidden();
  };
  await open();
  const pane=page.locator('.question-pane:not([hidden]):not([inert])');
  const frame=page.frameLocator('.question-pane:not([hidden]):not([inert]) iframe.question-frame');
  await expect(frame.locator('.qf-answer-shared textarea')).toBeVisible();
  await frame.locator('.qf-answer-shared textarea').fill('本次答案包含文字、图片和手写。');
  const png=Buffer.from(await page.evaluate(()=>{const canvas=document.createElement('canvas');canvas.width=80;canvas.height=40;const ctx=canvas.getContext('2d');ctx.fillStyle='#386db6';ctx.fillRect(0,0,80,40);return canvas.toDataURL('image/png').split(',')[1];}),'base64');
  const fixture=resolve('../.artifacts',`answer-${info.project.name}.png`);await mkdir(resolve('../.artifacts'),{recursive:true});await writeFile(fixture,png);
  const upload=page.waitForResponse(response=>new URL(response.url()).pathname==='/api/resources'&&response.request().method()==='POST');
  await frame.getByLabel('上传图片',{exact:true}).setInputFiles(fixture);
  expect((await upload).status()).toBe(200);
  await expect(frame.locator('.qf-answer-shared-picture')).toHaveCount(1);
  const draw=async(notes=false)=>{
    const tools=pane.locator('.qf-whiteboard-toolbar');
    if(await tools.getAttribute('data-collapsed')==='true')await tools.getByRole('button',{name:/展开白板工具/}).click();
    await tools.getByRole('button',{name:'画笔，选中后再次点击选择颜色',exact:true}).click();
    const surface=frame.locator('.qf-answer-shared-surface');await surface.scrollIntoViewIfNeeded();
    const rect=await pane.locator('iframe.question-frame').evaluate(frame=>{
      const bounds=frame.getBoundingClientRect(),[x,y,width,height]=frame.qfSharedAnswerAreas[0].rect;
      const sx=bounds.width/frame.clientWidth,sy=bounds.height/frame.clientHeight;
      return {x:bounds.left+x*sx,y:bounds.top+y*sy,width:width*sx,height:height*sy};
    }),y=rect.y+rect.height*(notes?.7:.45);
    await page.mouse.move(rect.x+rect.width*.35,y);await page.mouse.down();
    await page.mouse.move(rect.x+rect.width*.55,y+Math.min(15,rect.height*.08),{steps:10});await page.mouse.up();
  };
  await page.locator('#draft-toggle').click();
  await draw();
  await expect.poll(async()=>JSON.stringify((await read()).state.answer)).toContain('"strokes":[{');
  await expect.poll(async()=>(await read()).whiteboard.draft.strokes.length).toBeGreaterThan(0);
  await pane.getByLabel('白板层',{exact:true}).selectOption('notes');
  await draw(true);
  await expect.poll(async()=>(await read()).whiteboard.notes.strokes.length).toBeGreaterThan(0);
  await pane.getByLabel('白板层',{exact:true}).selectOption('draft');
  await pane.getByRole('button',{name:'操作题目或移动白板',exact:true}).click();
  await page.locator('#draft-toggle').click();
  const beforeSubmit=await read();
  for(const stroke of beforeSubmit.whiteboard.notes.strokes)expect(JSON.stringify(beforeSubmit.state.answer)).not.toContain(stroke.id);
  const submitted=page.waitForResponse(response=>new URL(response.url()).pathname===path+'/actions'&&response.request().postDataJSON().action==='submit');
  await frame.getByRole('button',{name:'提交',exact:true}).click();
  const reply=await submitted;expect(reply.status()).toBe(200);
  const value=await reply.json();expect(value.state.status).toBe('submitted');
  expect(value.question.data._qfSubmission.screenshots).toHaveLength(1);
  const snapshot=value.question.data._qfSubmission.screenshots[0].assetId;
  const image=await page.request.get(`/api/resources/${snapshot}`);expect(image.status()).toBe(200);
  expect(image.headers()['content-type']).toMatch(/^image\/png/);
  const range=await page.request.get(`/api/resources/${snapshot}`,{headers:{Range:'bytes=0-7'}});expect(range.status()).toBe(206);
  expect([...await range.body()]).toEqual([137,80,78,71,13,10,26,10]);
  const layers=value.whiteboard;
  await expect(frame.locator('.qf-answer-shared-snapshot')).toBeVisible();
  await expect.poll(()=>frame.locator('.qf-answer-shared-snapshot').evaluate(img=>img.complete&&img.naturalWidth>0)).toBe(true);
  await open();
  await expect(frame.locator('.qf-answer-shared-snapshot')).toBeVisible();
  const fresh=await read();expect(fresh.whiteboard).toEqual(layers);
  expect(fresh.question.data._qfSubmission.screenshots[0].assetId).toBe(snapshot);
  const directory=resolve(process.env.QF_SCREENSHOT_DIR||'../.artifacts/screenshots');await mkdir(directory,{recursive:true});
  await page.screenshot({path:resolve(directory,`whiteboard-resources-${info.project.name}.png`),fullPage:true});
  await page.locator('#draft-toggle').click();
  await pane.getByLabel('白板层',{exact:true}).selectOption('notes');
  await page.screenshot({path:resolve(directory,`whiteboard-layers-${info.project.name}.png`),fullPage:true});
  expect(errors).toEqual([]);
});
